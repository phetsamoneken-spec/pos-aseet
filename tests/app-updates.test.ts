import assert from 'node:assert/strict';
import { announceAppUpdate, isAppUpdateReady, startAppUpdateChecks, subscribeToAppUpdates } from '../src/services/appUpdates';
const windowEvents = new EventTarget();
const documentEvents = new EventTarget();
const documentMock = Object.assign(documentEvents, { visibilityState: 'visible' });
const windowMock = Object.assign(windowEvents, { setInterval, clearInterval });
Object.assign(globalThis, { window: windowMock, document: documentMock });
let checks = 0;
const cleanup = startAppUpdateChecks({ update: async () => { checks++; } } as unknown as ServiceWorkerRegistration);
await new Promise(r => setTimeout(r, 0));
assert.equal(checks, 1);
windowEvents.dispatchEvent(new Event('focus'));
await new Promise(r => setTimeout(r, 0));
assert.equal(checks, 2);
documentMock.visibilityState = 'hidden';
windowEvents.dispatchEvent(new Event('focus'));
await new Promise(r => setTimeout(r, 0));
assert.equal(checks, 2);
documentMock.visibilityState = 'visible';
documentEvents.dispatchEvent(new Event('visibilitychange'));
await new Promise(r => setTimeout(r, 0));
assert.equal(checks, 3);
let notifications = 0;
const unsubscribe = subscribeToAppUpdates(() => { notifications++; });
assert.equal(isAppUpdateReady(), false);
announceAppUpdate();
assert.equal(isAppUpdateReady(), true);
assert.equal(notifications, 1);
unsubscribe(); cleanup();
windowEvents.dispatchEvent(new Event('focus'));
await new Promise(r => setTimeout(r, 0));
assert.equal(checks, 3);
console.log('PASS: initial/focus/visibility update checks, hidden-tab suppression, update-ready notification, listener cleanup.');
