import assert from 'node:assert/strict';
const values=new Map<string,string>();
const ls={getItem:(key:string)=>values.get(key)??null,setItem:(key:string,value:string)=>{values.set(key,value)},removeItem:(key:string)=>{values.delete(key)}};
Object.assign(globalThis,{window:{localStorage:ls},localStorage:ls});
const {storage}=await import('../src/services/storage');
const {GasService}=await import('../src/services/gasService');
const admin={...storage.getCurrentUser()!};
const header=['MDE','Customer Code','Customer Name','Condition Quantity','Condition UOM','Product','Commencing On','Expiring On'];
const row=['MDE-B1','POLICY-1','Admin store',2,'CAS','Product','2026-01-01','2028-01-01'];
assert.equal(storage.importCustomersFromRawRows([header,row]).success,true);
assert.equal(storage.addTransaction({customerCode:'POLICY-1',amount:120000,category:'Other',description:'Actual spending',date:'2026-11-01'}).success,true);
const history=storage.getTransactions({customerCode:'POLICY-1'});
assert.equal(storage.importCustomersFromRawRows([header,[...row.slice(0,3),3,...row.slice(4)]],{replaceAll:true}).success,true);
assert.deepEqual(storage.getCustomers().map(c=>c.code),['POLICY-1']);
assert.equal(storage.getBudgetForCustomer('POLICY-1')!.totalUsed,120000);
assert.equal(storage.getBudgetForCustomer('POLICY-1')!.annualAmount,720000);
assert.equal(storage.getBudgetForCustomer('POLICY-1')!.remainingAmount,600000);
assert.deepEqual(storage.getTransactions({customerCode:'POLICY-1'}),history);
const before=JSON.stringify(storage.exportBusinessBackup());
assert.equal(storage.importCustomersFromRawRows([header,row,row],{replaceAll:true}).success,false);
assert.equal(JSON.stringify(storage.exportBusinessBackup()),before,'invalid master imports must not partially change data');
storage.setCurrentUser({...admin,id:'team-user',username:'team-one',role:'TEAM_USER',team:'B1'});
const settings=JSON.stringify(storage.getSettings());
assert.equal(storage.importCustomersFromRawRows([header,row],{replaceAll:true}).success,false);
assert.equal(storage.importCustomersFromCsv('MDE,Code,Name\nMDE-B1,OTHER,Other').success,false);
assert.throws(()=>storage.updateSettings({pricePerCrate:1}),/Admin permission/);
assert.throws(()=>storage.resetToSeedData(),/Admin permission/);
assert.equal(storage.recalculateBudgetsByPricePerCrate(1).success,false);
assert.equal((await GasService.saveSharedSettings()).success,false);
assert.equal(JSON.stringify(storage.exportBusinessBackup()),before);
assert.equal(JSON.stringify(storage.getSettings()),settings);
storage.setCurrentUser(null);
assert.equal(storage.importCustomersFromRawRows([header,row]).success,false);
assert.throws(()=>storage.updateSettings({language:'en'}),/Admin permission/);
console.log('PASS: Admin-only Excel/CSV/settings/reset, prevalidated master replacement, retained transaction history and recalculated budgets without resetting spending.');
